function config = plannerConfiguration(root, logDirectory, diagnosticsEnabled, formulation)
%PLANNERCONFIGURATION 由 MATLAB 明确选择数值后端使用的模型、配置和日志路径。
% MEX 只消费这些路径，不再推断应用目录结构或安排求解时刻。
if nargin < 3, diagnosticsEnabled = true; end
if nargin < 4, formulation = 'whole_body'; end
configurationDirectory = fullfile(root,'config');
if strcmp(formulation,'centroidal')
    configurationDirectory = fullfile(configurationDirectory,'centroidal');
elseif ~strcmp(formulation,'whole_body')
    error('G1:PlannerMex','Unknown MPC formulation');
end
config = struct( ...
    'taskFile', fullfile(configurationDirectory, 'task.info'), ...
    'referenceFile', fullfile(configurationDirectory, 'reference.info'), ...
    'urdfFile', fullfile(root, 'assets', 'g1_29dof.urdf'), ...
    'logDirectory', logDirectory, ...
    'diagnosticsEnabled', diagnosticsEnabled, ...
    'formulation', formulation);
end
